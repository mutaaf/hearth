// Writes web/brand-icons.js: vector logos for the app catalog (src/catalog.js)
// from Simple Icons (CC0), pinned. Only brands Simple Icons carries: Prime
// Video, Disney+, Hulu, Peacock, ESPN, Pluto TV and Sling asked to be left out
// there, so they keep a lettered tile unless a TV hands over its own icon.
//   node scripts/brand-icons.mjs
import { writeFileSync } from 'node:fs';

const VERSION = '16.36.0';
const SLUGS = {
  youtube: 'youtube', youtubetv: 'youtubetv', netflix: 'netflix', max: 'hbomax', appletv: 'appletv',
  paramountplus: 'paramountplus', spotify: 'spotify', plex: 'plex', tubi: 'tubi', fubo: 'fubo',
  twitch: 'twitch', crunchyroll: 'crunchyroll', youtubekids: 'youtubekids',
};
const out = {};
for (const [key, slug] of Object.entries(SLUGS)) {
  const svg = await (await fetch(`https://cdn.jsdelivr.net/npm/simple-icons@${VERSION}/icons/${slug}.svg`)).text();
  const d = svg.match(/ d="([^"]+)"/)?.[1];
  if (!d) throw new Error(`no path for ${slug}`);
  out[key] = d;
}
writeFileSync(
  new URL('../web/brand-icons.js', import.meta.url),
  `// Generated by scripts/brand-icons.mjs from Simple Icons ${VERSION} (CC0; https://simpleicons.org).
// One 24×24 SVG path per catalog key. Logos are their owners' trademarks, shown
// only to label the button that opens that app. Don't edit; re-run the script.
export const BRAND_PATHS = ${JSON.stringify(out, null, 0).replace(/","/g, '",\n  "').replace('{"', '{\n  "').replace('"}', '",\n}')};
`,
);
console.log(`web/brand-icons.js: ${Object.keys(out).length} logos`);
